/**
 * Scans public/gallery/<category>/*.png and generates lib/gallery.ts
 * so the gallery page always stays in sync with the images on disk.
 *
 * Re-run with:  npm run gallery:build
 */
import {
  readFileSync,
  readdirSync,
  writeFileSync,
  mkdirSync,
  existsSync,
} from "node:fs";
import { dirname } from "node:path";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(import.meta.url), "../../");
const galleryDir = join(root, "public", "gallery");
const outFile = join(root, "lib", "gallery.ts");

const naturalCompare = (a, b) =>
  a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

const CATEGORY_LABELS = {
  featured: "Featured",
  event: "Event & Competition",
  logo: "Logo Design",
  print: "Print & Collateral",
  social: "Social Media",
  shirts: "T-Shirt & Apparel",
};

function pngSize(file) {
  const buf = readFileSync(file);
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

function humanize(slug) {
  let t = slug
    .replace(/-/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
  // drop "prev / preview / test / v2" style suffix words from filenames
  t = t.replace(/\b(Prev|Preview|Test|V[0-9]|@2x|2x|Copy)\b/g, " ");
  return t.replace(/\s+/g, " ").trim() || "Untitled";
}

const categories = Object.keys(CATEGORY_LABELS);
const items = [];

for (const cat of categories) {
  const dir = join(galleryDir, cat);
  if (!existsSync(dir)) continue;
  for (const file of readdirSync(dir).sort(naturalCompare)) {
    if (!file.toLowerCase().endsWith(".png")) continue;
    const src = join(dir, file);
    const slug = file.replace(/\.png$/i, "");
    const { w, h } = pngSize(src);
    items.push({
      src: `/gallery/${cat}/${file}`,
      title: humanize(slug),
      category: CATEGORY_LABELS[cat],
      categorySlug: cat,
      w,
      h,
    });
  }
}

const indent = (o) => JSON.stringify(o, null, 2).replace(/\n/g, "\n  ");
const lines = items.map((i) => `  ${indent(i)},`);

const output = `// Auto-generated by scripts/build-gallery-data.mjs — do not edit by hand.
// Re-run \`npm run gallery:build\` after adding images to public/gallery/.

export type GalleryItem = {
  src: string;
  title: string;
  category: string;
  categorySlug: string;
  w: number;
  h: number;
};

export const galleryCategories: { slug: string; label: string }[] = [
  ${categories.map((c) => `{ slug: "${c}", label: "${CATEGORY_LABELS[c]}" },`).join("\n  ")}
];

export const galleryItems: GalleryItem[] = [
${lines.join("\n")}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, output);
console.log(`Wrote ${outFile} with ${items.length} items.`);
